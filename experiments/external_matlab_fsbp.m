function external_matlab_fsbp()
% Run the original FSBP code to emit standalone Julia data.
reference = getenv('FSBP_REFERENCE');
assert(isfolder(reference), 'Set FSBP_REFERENCE to the original FSBP checkout');
addpath(reference);
if exist('lsqminnorm', 'file') == 0 && exist('lsqminnorm', 'builtin') == 0
    addpath(fullfile(fileparts(mfilename('fullpath')), 'octave_compat'));
end

fprintf('# Generated by experiments/external_matlab_fsbp.m.\n');
fprintf('# FSBP e82d787d7c61b89d7aa98715cbd294d726ec28b8, BSD-2-Clause.\n');
fprintf('const EXTERNAL_MATLAB_FSBP = (\n');
run_case('poly', 'Lobatto', 3);
run_case('trig', 'equid', 3);
fprintf(')\n');
end

function run_case(space, points, count)
    [x, w] = compute_QF(0, 1, space, points, count);
    [basis, derivatives] = generate_span(0, 1, space, points, count);
    [D, P, Q] = compute_FSBP(basis, derivatives, x, w);
    X = zeros(length(x), count);
    Y = X;
    for i = 1:length(x)
        X(i,:) = basis(x(i))';
        Y(i,:) = derivatives(x(i))';
    end
    fprintf('    (; name=:%s, x=vec(Float64[', space);
    fprintf(' %.17g', x);
    fprintf(']),\n        weights=vec(Float64[');
    fprintf(' %.17g', diag(P));
    fprintf(']),\n');
    write_matrix('D', D);
    write_matrix('Q', Q);
    write_matrix('X', X);
    write_matrix('Y', Y);
    fprintf('    ),\n');
end

function write_matrix(name, values)
    fprintf('        %s=Float64[\n', name);
    for i = 1:size(values, 1)
        fprintf('           ');
        fprintf(' %.17g', values(i,:));
        fprintf(';\n');
    end
    fprintf('        ],\n');
end
