# Regenerate the standalone rational fixture from the pinned external package.
import SummationByPartsOperators as Upstream
using LinearAlgebra

function rational_literal(x)
    iszero(x) && return "0"
    isone(denominator(x)) && return string(numerator(x))
    return string(numerator(x), "//", denominator(x))
end

function emit_matrix(io, name, data)
    if size(data, 1) == 1
        println(io, "        ", name, "=reshape(Rational{BigInt}[",
                join(rational_literal.(vec(data)), ", "), "], 1, :),")
        return
    end
    println(io, "        ", name, "=Rational{BigInt}[")
    for i in axes(data, 1)
        println(io, "            ", join(rational_literal.(data[i, :]), " "), ";")
    end
    println(io, "        ],")
end

println("# Generated by experiments/external_classical.jl with")
println("# SummationByPartsOperators.jl v0.5.106-DEV, commit 20f6b1293622fd6afef062b5fc8780b5b617af47.")
println("# Upstream MIT license, copyright Hendrik Ranocha and contributors.")
println("const EXTERNAL_CLASSICAL = (")
for (p, depth) in ((2,1), (4,4), (6,6), (8,8))
    N = 41
    radius = p ÷ 2
    op = Upstream.derivative_operator(Upstream.MattssonNordström2004(), 1, p,
                                      big(0)//1, big(N-1)//1, N)
    H, D = Matrix(Upstream.mass_matrix(op)), Matrix(op)
    Q = H * D
    left = 1:depth
    m = depth + radius + 1
    eltype(Q) === Rational{BigInt} || error("expected genuinely exact reference coefficients")
    println("    (order=", p, ", depth=", depth, ",")
    emit_matrix(stdout, "H", H[left,left])
    emit_matrix(stdout, "Q", Q[left, 1:(depth+radius)])
    emit_matrix(stdout, "center", Q[m:m, (m-radius):(m+radius)])
    println("    ),")
end
println(")")
